"""Сборка сообщений клиенту: человеческая оболочка вокруг дословных фактов.

Владелец 25.07.2026: «агент даже не поздоровался с клиентом, ну где вежливость».

Причина была структурной, а не в формулировках. У агента два канала вывода: модель (пишет
по-человечески) и КОД (отправляет факты дословно — условия из документа, сверку анкеты, служебные
строки). Второй канал шёл мимо всякой человечности, поэтому люди получали первым сообщением
голое «Вижу анкету: • Ссылка на магазин…» (диалог 256942600) или «Уточню это у команды и вернусь
с ответом» (диалог 1451982360) — без приветствия, без имени, без единого живого слова.

Здесь собирается ЛЮБОЕ сообщение, которое отправляет код. Дословная часть остаётся неприкосновенной
(её сверяет `verbatim_intact`), а вокруг появляется то, что делает живой менеджер: обращение по
имени при первом контакте и короткая подводка к документу.

Тон — по `docs/tone-of-voice.md`: снижать усилие клиента, признавать сказанное, один вопрос за
сообщение, никакого канцелярита.
"""
from __future__ import annotations

GREETING = "Здравствуйте"

# Подводки к дословным блокам. Документ не трогаем — но и не вываливаем молча.
LEAD_IN_TERMS = "Рассказываю про условия — ниже всё дословно, как есть:"
LEAD_IN_ANKETA = "Спасибо, анкету получил! Давайте сверим, всё ли я вижу правильно:"


def greeting_for(name: str = "") -> str:
    """«Здравствуйте, Александр!» — имя, если оно известно."""
    clean = " ".join(str(name or "").split()).strip(" ,.!")
    return f"{GREETING}, {clean}!" if clean else f"{GREETING}!"


def compose(body: str, *, name: str = "", greet: bool = False,
            lead_in: str = "", follow_up: str = "") -> str:
    """Собрать сообщение клиенту: приветствие → подводка → дословный блок → следующий шаг.

    Пустые части просто отсутствуют, лишних пустых строк не остаётся."""
    parts = []
    if greet:
        parts.append(greeting_for(name))
    if lead_in:
        parts.append(lead_in.strip())
    parts.append((body or "").strip())
    if follow_up:
        parts.append(follow_up.strip())
    return "\n\n".join(p for p in parts if p)


def verbatim_intact(message: str, verbatim: str) -> bool:
    """Дословный блок дошёл до клиента слово в слово?

    Проверяем ПОСЛЕ сборки: оболочка имеет право добавить текст вокруг, но не внутри. Условия
    и сверка анкеты — это факты компании, их нельзя ни сократить, ни переписать."""
    return bool(verbatim) and verbatim.strip() in (message or "")
