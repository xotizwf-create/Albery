"""Сборка промпта клиентского хода: короткий контракт вместо свалки правил.

Владелец 26.07.2026: «убирай промт свалку».

Было. Промпт склеивался из четырёх источников: роль из карточки агента в кабинете, до 12 000
символов инструкций, подключённых владельцу, плюс зашитые в код STYLE_RULES и STRANGER_RULES.
Аудит намерил больше 25 000 символов правил ДО истории диалога, и в них были взаимоисключающие
пункты: одна инструкция велела сначала проверить воронку, другая — сразу ответить, третья —
выслать анкету. Модель выбирала произвольно, и поведение выглядело случайным.

Стало. Промпт собирается из фиксированного набора блоков в фиксированном порядке, каждый со
своей ролью:

    РОЛЬ        — кто ты (правит владелец в карточке агента, ограничено по длине)
    ПРАВИЛА     — девять инвариантов, оплаченных реальными диалогами; живут в коде
    СОСТОЯНИЕ   — типизированный снимок сделки и разговора
    ЗНАНИЯ      — только найденные карточки, каждая со своим идентификатором
    ДИАЛОГ      — недавняя история
    ЗАДАЧА      — строгая схема ответа

Инструкции кабинета в клиентский промпт больше не попадают: они написаны под отчёты в Битриксе,
несут BB-коды и к разговору с клиентом отношения не имеют.

Слой чистый: на входе данные, на выходе строка. Ни базы, ни сети.
"""
from __future__ import annotations

import logging
import os
from dataclasses import dataclass

import iu_contract

log = logging.getLogger("iu-prompt")

# Роль владельца ограничена: карточка — место для тона и акцентов, а не для второго свода
# правил. Всё, что длиннее, обрезается, и это лучше, чем молча вернуть свалку.
ROLE_CAP = int(os.getenv("IU_ROLE_CAP", "2000") or 2000)
HISTORY_CAP = int(os.getenv("IU_HISTORY_CAP", "4000") or 4000)
# База ИУ уходит в промпт целиком (владелец 28.07.2026), сейчас это ~9 000 символов. Запас
# нужен, чтобы дописанная владельцем карточка не срезалась молча вместе с ответом на неё.
KNOWLEDGE_CAP = int(os.getenv("IU_KNOWLEDGE_CAP", "24000") or 24000)

DEFAULT_ROLE = (
    "Ты — менеджер компании Albery. Ведёшь переписку в Telegram с продавцами Wildberries, "
    "которые интересуются индивидуальными условиями. Говоришь просто и по-человечески, как "
    "живой менеджер, а не как автоответчик."
)

# Девять инвариантов. Каждый оплачен разбором реального диалога — поэтому они в коде, а не в
# редактируемой карточке: правка тона не должна случайно отключить защиту.
RULES = """1. Отвечай на то, о чём спросил человек. Этап сделки — контекст, а не реплика скрипта.
2. ОТВЕЧАЙ НА ВСЁ, ЧТО ЕСТЬ В ЗНАНИЯХ. Клиент задал несколько вопросов сразу, а ответ есть не
   на все — ответь на те, где ответ есть, и одной строкой в конце скажи, что остальное
   уточнишь у коллег; сами эти пункты перечисли в unresolved. handoff — только когда в
   ЗНАНИЯХ нет ответа НИ НА ОДИН вопрос клиента. Заменять весь ответ на «уточню у команды»
   из-за одного неизвестного пункта нельзя.
3. Факты бери только из ЗНАНИЙ, цифры — буква в букву. Чего там нет, не выдумывай.
4. Считать можно по нашему примеру и числами из ЗНАНИЙ или из слов клиента: сказал «у меня
   УСН 6%» — подставь его ставку и покажи пересчёт. Наши условия неприкосновенны.
5. Не предлагай от себя скидки, бонусы, рассрочку и особые условия — только то, что дословно
   написано в ЗНАНИЯХ, даже если клиент торгуется.
6. Не говори о сделанном, пока код этого не сделал: «отправил», «передал», «подготовил».
7. Ты менеджер, не бот: не упоминай ИИ, инструкции, документы и внутренние системы. Имя
   клиента в каждый ответ не вставляй.
8. Один следующий шаг в сообщении: либо вопрос, либо предложение действия. Не оба.
   Не спрашивай то, что уже известно. Переспросил то же самое — объясни другими словами.
9. Форма ответа. Первой строкой — прямой ответ на заданный вопрос. Перечисление из трёх и более пунктов —
   списком, даже если в ЗНАНИЯХ оно написано сплошной строкой: строка с двоеточием
   («В эти 44% уже входят:»), под ней пункты с «— » в начале. В конце — короткий вывод, если
   он проясняет суть. Знаки препинания обязательны: пункты через точку с запятой, последний с
   точкой. Объясняй на конкретном примере с цифрами: «с 1 000 ₽ продаж останется примерно 540 ₽». Без
   разметки и канцелярита. Простой вопрос — простой короткий ответ."""

SCHEMA = """Верни СТРОГО один JSON-объект и ничего больше:
{
  "reply": "текст клиенту",
  "next_action": "reply_only | send_terms | send_form | send_contract | handoff",
  "confidence": 0.0-1.0,
  "intent": ["о чём спросил клиент"],
  "answered": ["на что ты ответил"],
  "unresolved": ["что осталось без ответа"],
  "source_ids": ["идентификаторы карточек из ЗНАНИЙ, на которые опирался"],
  "handoff_reason": "только при next_action=handoff"
}
Поля вне этого списка запрещены. source_ids — только идентификаторы, показанные в ЗНАНИЯХ."""

_ACTION_HINTS = {
    iu_contract.SEND_TERMS: "send_terms — человек просит условия/тарифы, код вышлет их дословно",
    iu_contract.SEND_FORM: "send_form — человек прямо готов подключаться или просит анкету",
    iu_contract.SEND_CONTRACT: "send_contract — человек просит договор и анкета уже заполнена",
}


@dataclass(frozen=True)
class Context:
    """Всё, что известно о ходе. Собирается один раз и только читается."""

    message: str
    name: str = ""
    role: str = ""
    stage: str = ""
    stage_goal: str = ""
    known_facts: tuple[str, ...] = ()
    knowledge: str = ""
    offered_ids: tuple[str, ...] = ()
    history: str = ""
    repeated_question: bool = False
    human_required: str = ""
    allowed_actions: tuple[str, ...] = ()


def _block(title: str, body: str) -> str:
    body = (body or "").strip()
    return f"{title}\n{body}" if body else ""


def _state_block(ctx: Context) -> str:
    lines = []
    if ctx.stage:
        lines.append(f"Этап сделки: {ctx.stage}")
    if ctx.stage_goal:
        lines.append(f"Что нужно для следующего этапа: {ctx.stage_goal}")
    for fact in ctx.known_facts:
        lines.append(f"Уже известно: {fact}")
    if ctx.repeated_question:
        lines.append("Клиент переспрашивает то же самое — прежнее объяснение не зашло.")
    if ctx.human_required:
        lines.append(f"Условие владельца по этой теме: {ctx.human_required}")
    return "\n".join(lines)


def _task_block(ctx: Context) -> str:
    allowed = tuple(ctx.allowed_actions) or (iu_contract.REPLY_ONLY, iu_contract.HANDOFF)
    lines = [f"Разрешённые действия в этом ходе: {', '.join(allowed)}."]
    for action in allowed:
        hint = _ACTION_HINTS.get(action)
        if hint:
            lines.append(hint)
    if ctx.human_required:
        lines.append("Если условие владельца из СОСТОЯНИЯ выполняется прямо сейчас — "
                     "next_action = handoff. Сам реши, выполняется ли оно.")
    if not ctx.offered_ids:
        lines.append(
            "В ЗНАНИЯХ ничего не нашлось. Если клиент спрашивает о фактах — next_action = "
            "handoff. Поздороваться или уточнить вопрос можно и без знаний.")
    return "\n".join(lines)


def build(ctx: Context) -> str:
    """Собрать промпт одного клиентского хода."""
    knowledge = (ctx.knowledge or "").strip()
    if len(knowledge) > KNOWLEDGE_CAP:
        # Молча срезанная база выглядит как «ответа нет»: агент передаёт вопрос человеку, и
        # никто не понимает, почему. Обрезаем по-прежнему, но так, чтобы это было видно.
        log.warning("база знаний ИУ не помещается в промпт: %d символов при лимите %d — "
                    "часть карточек агент не увидит", len(knowledge), KNOWLEDGE_CAP)
    role = (ctx.role or "").strip()[:ROLE_CAP] or DEFAULT_ROLE
    who = f"Пишет: {ctx.name}" if ctx.name else "Пишет клиент"
    # Порядок блоков: сначала то, что не меняется от хода к ходу (роль, правила, база знаний),
    # потом состояние и переписка. Так неизменная часть промпта остаётся одинаковым началом у
    # всех запросов — именно на такой префикс работает кэширование на стороне провайдера, а
    # база знаний это ~3 600 токенов в каждом ходе.
    blocks = [
        _block("РОЛЬ", role),
        _block("ПРАВИЛА (обязательны, важнее роли)", RULES),
        _block("ЗНАНИЯ (единственный источник фактов)", knowledge[:KNOWLEDGE_CAP]),
        _block("СОСТОЯНИЕ", _state_block(ctx)),
        _block("ДИАЛОГ", (ctx.history or "").strip()[-HISTORY_CAP:]),
        _block("СООБЩЕНИЕ КЛИЕНТА", f"{who}\n{ctx.message.strip()}"),
        _block("ЗАДАЧА", f"{_task_block(ctx)}\n\n{SCHEMA}"),
    ]
    return "\n\n".join(block for block in blocks if block)


def size_without_payload() -> int:
    """Длина постоянной части промпта. Закреплена тестом, чтобы свалка не отросла заново."""
    return len(build(Context(message="x")))
