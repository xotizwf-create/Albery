from __future__ import annotations

# Поиск по базе знаний ИУ на ЖИВЫХ вопросах клиентов из переписок, а не на формулировках,
# переписанных из самой базы. Владелец 28.07.2026: агент не отвечал на такие вопросы —
# лексического совпадения не хватало, и ход уходил в «уточню у команды».

import iu_knowledge

# Сокращённые карточки настоящей базы (документ владельца, 28.07.2026).
CARDS = iu_knowledge.parse_qa("""
1. Какая комиссия будет у Вас? Сколько я буду получать? Какая комиссия ВБ?

Ответ: Базовая комиссия по программе составляет 44% от суммы реализации товара. В неё входят
комиссия Wildberries, логистика, включая обратную, хранение и приёмка, а также наша агентская
комиссия. Эквайринг составляет ориентировочно 2% и удерживается дополнительно.

2. От какой суммы считается процент?

Ответ: Процент рассчитывается от суммы реализации товара (до СПП), а не от суммы, которую
Wildberries перечисляет после своих удержаний. Пример: реализация 1 000 000 ₽, удержания
ориентировочно 46%, к перечислению остаётся 540 000 ₽.

3. Кто оплачивает рекламу?

Ответ: Рекламой вы управляете самостоятельно: выбираете товары, бюджеты и кампании. Требований
к ДРР со стороны программы нет. Расходы на рекламу оплачиваются за ваш счёт.

4. Как определяется налоговая база?

Ответ: Налоги селлер рассчитывает и уплачивает самостоятельно в соответствии со своей системой
налогообложения. Для управленческого расчёта можно ориентироваться на сумму реализации за
вычетом СПП. Для селлера на УСН «Доходы» ориентировочный налог считается с этой базы. Для ОСНО
порядок расчёта НДС и налога на прибыль зависит от договорной схемы и первичных документов.

5. Можно ли получить договор заранее?

Ответ: Да. До заключения сделки мы направляем обезличенный проект договора комиссии для
изучения. В договоре описаны порядок работы с товаром, расчёты, «Честный знак», обязанности
сторон, ответственность, возвраты, реклама и порядок выплат.

7. Кому доступен взнос 200 000 ₽ вместо 500 000 ₽?

Ответ: Стандартный единоразовый взнос за подключение — 500 000 ₽. Для первых подключений в
рамках текущей программы возможна стоимость 200 000 ₽.

8. Сколько занимает подключение?

Ответ: Ориентировочный срок подключения — до 3 рабочих дней при наличии полного комплекта
документов и своевременном предоставлении доступов.

11. Кому подходит программа и какие ограничения?

Ответ: Программа рассчитана на селлеров с оборотом от 3 000 000 ₽ в месяц. Работаем с
большинством товарных категорий.

12. С какой формой собственности и системой налогообложения можно работать?

Ответ: Подключаем индивидуальных предпринимателей и ООО. Возможен любой режим налогообложения
при условии, что селлер самостоятельно обеспечивает корректный налоговый учёт.

15. Как будет вестись управление кабинетом?

Ответ: Товар продаётся через наш кабинет продавца. Вы получаете доступ к платформе, где можно
менять цены, создавать карточки, управлять скидками, отвечать на отзывы и оформлять поставки.
""")

# Вопрос клиента → карточка, которая на него отвечает. Формулировки взяты из живых переписок
# 27–28.07.2026 без правок.
REAL_QUESTIONS = [
    ("Ваша компания на осно?", "Как определяется налоговая база?"),
    ("Какой взнос?", "Кому доступен взнос 200 000 ₽ вместо 500 000 ₽?"),
    ("Какая у вас агентская комиссия?", "Какая комиссия будет у Вас?"),
    ("А налоги как мне считать? Вот у меня налог 6% усн", "Как определяется налоговая база?"),
    ("Можете Пожалуйста прислать договор?", "Можно ли получить договор заранее?"),
    ("У нас будет доступ для формирования поставок через ваш лк?", "Как будет вестись управление кабинетом?"),
    ("Это будет на вашем кабинете или на моем кабинете подключат иу?", "Как будет вестись управление кабинетом?"),
    ("Какой дрр нужно держать?", "Кто оплачивает рекламу?"),
    ("Оборот 30млн, планируемый 30-50млн", "Кому подходит программа и какие ограничения?"),
]


def _top(question: str):
    found = iu_knowledge.search(question, CARDS)
    return (found[0].card.title, found[0].score) if found else ("", 0.0)


def test_real_questions_find_the_right_card():
    misses = []
    for question, expected in REAL_QUESTIONS:
        title, _score = _top(question)
        if title != expected:
            misses.append(f"«{question[:45]}» → {title or 'ничего'} (ждали {expected[:40]})")
    assert not misses, "не нашли карточку на живые вопросы:\n" + "\n".join(misses)


def test_found_card_is_enough_for_the_turn_to_pass():
    """Проверяем не абстрактный скор, а то, доедет ли ответ до клиента.

    Уверенность хода складывается из поиска, опоры на источник и самооценки модели. Поиск —
    самая весомая часть, и раньше он проваливал ход даже там, где карточка найдена верно.
    """

    import iu_contract

    weak = []
    for question, _expected in REAL_QUESTIONS:
        found = iu_knowledge.search(question, CARDS)
        card = found[0].card
        plan = iu_contract.TurnPlan(
            reply=card.answer[:200],
            next_action=iu_contract.REPLY_ONLY,
            confidence=0.9,
            source_ids=(card.id,),
        )
        verdict = iu_contract.assess(
            plan,
            retrieval=iu_knowledge.retrieval_score(found),
            sources_text=iu_knowledge.sources_text(found),
            message=question,
        )
        if not verdict.allowed:
            weak.append(f"«{question[:45]}» → {verdict.score:.2f}: {'; '.join(verdict.reasons)[:70]}")
    assert not weak, "ход с найденной карточкой не доходит до клиента:\n" + "\n".join(weak)


def test_calculation_question_still_finds_the_right_card():
    """Расчёт клиента проверяет человек (строгий порог в контракте), но карточка обязана найтись."""

    title, _ = _top("погодите, я продал на 1 000 000руб, вб вам перечисляет 750 000, а мне 750 000 - 44%?")

    assert title == "От какой суммы считается процент?"


def test_question_outside_the_base_still_goes_to_a_human():
    """Обратная защита: чего в базе нет, то и не находится."""

    for question in ("А вы отправляете товар в Казахстан?",
                     "Можно у вас арендовать склад в Москве?",
                     "Вы делаете фотосъёмку карточек?"):
        found = iu_knowledge.search(question, CARDS)
        assert iu_knowledge.retrieval_score(found) < 0.6, (
            f"«{question}» не должен уверенно находить карточку"
        )


def test_rare_words_weigh_more_than_common_ones():
    """«осно» и «дрр» встречаются в базе редко и потому определяют тему вопроса."""

    title, _ = _top("осно")
    # Слово встречается ровно в одной карточке — она и должна найтись.
    assert title == "Как определяется налоговая база?"
    title, _ = _top("дрр")
    assert title == "Кто оплачивает рекламу?"


def test_real_calculation_request_is_still_judged_strictly():
    """Защита от вранья в расчётах остаётся: спор клиента 25.07.2026 стоил дорого."""

    import iu_contract

    plan = iu_contract.TurnPlan(
        reply="При цене 5000 ₽ и ДРР 15% на кабинет придёт примерно 2100 ₽.",
        next_action=iu_contract.REPLY_ONLY,
        confidence=0.9,
    )
    strict = "Хотел бы пример расчёта получить. Себес 950, цена до СПП 5000. Сколько я получу?"

    assert iu_contract.is_calculation(plan, strict) is True
    assert iu_contract.threshold_for(plan, strict) == iu_contract.CALC_THRESHOLD


def test_quoting_a_rate_from_the_base_is_not_a_calculation():
    """Цитата ставки — не расчёт: её защищает вето на числа без источника."""

    import iu_contract

    plan = iu_contract.TurnPlan(
        reply="Программа рассчитана на селлеров с оборотом от 3 000 000 ₽ в месяц.",
        next_action=iu_contract.REPLY_ONLY,
        confidence=0.9,
    )

    assert iu_contract.is_calculation(plan, "Оборот 30млн, планируемый 30-50млн") is False
    assert iu_contract.threshold_for(plan, "Какой у вас минимальный оборот?") == iu_contract.THRESHOLD
