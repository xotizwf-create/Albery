-- Кто последним правил автоматизацию из диалога.
--
-- Агент получил право менять сценарий уже существующей автоматизации, в том числе заведённой
-- владельцем в приложении.  Авторство строки (created_by/creator_label) при этом не меняется:
-- оно отвечает на вопрос «кто её завёл», а не «кто трогал последним».  Без отдельного следа
-- правка из чата была бы невидимой — владелец увидел бы чужой сценарий под своим именем.

ALTER TABLE agent_automations
    ADD COLUMN IF NOT EXISTS last_edited_by text,
    ADD COLUMN IF NOT EXISTS last_edited_at timestamptz;
