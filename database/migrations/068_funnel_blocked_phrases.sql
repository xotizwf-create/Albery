-- 068_funnel_blocked_phrases.sql
-- Idempotent. Список запрещённых фраз воронки: при их наличии агент отказывается отвечать.
--
-- Why: владелец 26.07.2026 — «обязательно реализовать фильтры. Заблокированные фразы:
-- указываются слова или фразы (по одной на строку), при наличии которых бот откажется отвечать.
-- Вместо ответа клиент получит стандартное сообщение о невозможности помочь по этой теме».
-- Названные применения: конкуренты, нецензурная лексика, темы вне бизнеса, jailbreak.
--
-- Список живёт там же, где выключатель агента и режим тестирования: строка funnel_scenarios с
-- stage_id='' — это настройки воронки целиком. Отдельная таблица не заводится намеренно: у
-- настроек воронки уже есть кэш, история правок и инвалидация, и второе хранилище пришлось бы
-- синхронизировать.
--
-- Одна фраза на строку; строки, начинающиеся с #, считаются комментарием; префикс re: означает
-- готовую регулярку. Разбор — iu_filters.parse_phrases.
ALTER TABLE funnel_scenarios
    ADD COLUMN IF NOT EXISTS blocked_phrases text NOT NULL DEFAULT '';

COMMENT ON COLUMN funnel_scenarios.blocked_phrases IS
    'Для stage_id='''': запрещённые фразы, по одной на строку (# — комментарий, re: — регулярка).';
