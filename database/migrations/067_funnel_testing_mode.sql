-- 067_funnel_testing_mode.sql
-- Idempotent. Режим тестирования воронки: эскалации уходят в тестовую группу, а не в рабочую.
--
-- Why: владелец 25.07.2026 — «пока что сообщения-эскалации пусть уходят от клиентов в другую
-- группу; во вкладке воронки сделай надпись „Идёт тестирование“ и галочку». Пока база знаний по
-- ИУ не наполнена, агент часто не находит ответ и уносит вопрос людям. На время наладки этот
-- поток не должен сыпаться в рабочую группу «Работа с ИУ» (chat2424) — иначе люди перестанут
-- отличать реальные вопросы клиентов от шума проверок.
--
-- Флаг живёт там же, где выключатель агента: строка funnel_scenarios с stage_id='' — это
-- настройки воронки целиком. Отдельная таблица не заводится намеренно: у настроек воронки уже
-- есть кэш, история правок и инвалидация, и второе хранилище пришлось бы синхронизировать.
ALTER TABLE funnel_scenarios
    ADD COLUMN IF NOT EXISTS testing boolean NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN funnel_scenarios.testing IS
    'Для stage_id='''': идёт тестирование — эскалации агента уходят в тестовую группу.';
