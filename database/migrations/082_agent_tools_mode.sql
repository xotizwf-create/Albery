-- Набор инструментов агента задаётся РЕЖИМОМ, а не «уровнем доступа».
--
-- Зачем. В системе жили ДВА разных понятия с одним названием «уровень», и они путались:
--   * agent_access.tier — уровень ЧЕЛОВЕКА (admin/ops/faq/none);
--   * agents.tier       — уровень АГЕНТА (faq/ops/developer).
-- Первый перестал влиять на возможности ещё когда включили UNIVERSAL_MAIN_AGENT: все
-- допущенные сотрудники ходят через один коннектор agent-main и получают ЕГО набор
-- целиком, какой бы уровень им ни выставили в интерфейсе. То есть интерфейс обещал три
-- разных уровня, а по факту у всех был один. Второй решал, что достанется агенту, которому
-- набор не настраивали: «Агент Менеджер МП» так молча получил 134 инструмента — их ему
-- никто не выбирал.
--
-- Владелец 07.08.2026: «у нас есть базовый набор инструментов, который должен быть у любого
-- агента, есть максимальный набор, вот в чём отличия. Человеку выдаётся доступ, а
-- возможности агента зависят от инструментов и инструкций, которые к нему подключены».
--
-- Отсюда три режима вместо пресета по тиру:
--   base   — только базовый набор: прочитать свои инструкции и поискать по базе знаний.
--            Умолчание для НОВОГО агента: пустой агент безопаснее щедрого.
--   max    — весь реестр целиком, включая инструменты, добавленные завтра. Ровно то, что
--            нужно агенту-разработчику: новые возможности прилетают ему сами.
--   custom — явный список, выбранный владельцем в интерфейсе.
--
-- Совместимость и порядок применения. Колонка tier у агентов НЕ удаляется: её читают
-- интерфейс и аналитика, а снос колонки необратим. Она просто перестаёт участвовать в
-- вычислении набора. Бэкфилл ниже сохраняет текущее поведение всех агентов при одном
-- условии: перед этой миграцией должен быть выполнен scripts/materialize_agent_toolsets.py,
-- который записывает фактический набор в tools тем агентам, кто ехал на пресете. Скрипт
-- идемпотентен, у него есть --dry-run, и он ничего не меняет у агентов с явным списком.

ALTER TABLE agents
    ADD COLUMN IF NOT EXISTS tools_mode text NOT NULL DEFAULT 'base';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'agents_tools_mode_check'
    ) THEN
        ALTER TABLE agents
            ADD CONSTRAINT agents_tools_mode_check
            CHECK (tools_mode IN ('base', 'max', 'custom'));
    END IF;
END $$;

-- Бэкфилл существующих агентов: сохранить ровно тот набор, что у них сейчас.
-- Условие «tools_mode = 'base'» делает шаги идемпотентными — повторный прогон миграции
-- не переписывает режим, выбранный владельцем в интерфейсе после первого применения.

-- Явный список владельца → custom.
UPDATE agents
   SET tools_mode = 'custom'
 WHERE tools_mode = 'base'
   AND tools_customized;

-- Агент-разработчик ехал на пресете «весь реестр» и обязан продолжать: новые инструменты
-- должны появляться у него автоматически, иначе система теряет способность обслуживать себя.
UPDATE agents
   SET tools_mode = 'max'
 WHERE tools_mode = 'base'
   AND NOT tools_customized
   AND tier = 'developer';

-- Главный агент: убрать инструменты, которые раньше отсекал уровень человека.
--
-- Пока набор выбирался по уровню собеседника, эти семь инструментов доставались только
-- уровню «полный доступ». После перехода на единый коннектор agent-main их получили ВСЕ
-- 13 сотрудников с доступом — просто потому, что они лежат в наборе главного агента.
-- Никто такого решения не принимал, это побочный эффект прежнего перехода.
--
-- Решение владельца 07.08.2026: убрать все семь из набора главного агента. Возможность
-- никуда не девается — она включается явно тому агенту, которому нужна (у агента-разработчика
-- режим 'max', то есть весь реестр, включая эти инструменты). Идемпотентно: array_remove
-- на уже вычищенном списке ничего не меняет.
UPDATE agents
   SET tools = (
           SELECT coalesce(array_agg(t ORDER BY t), '{}')
             FROM unnest(tools) AS t
            WHERE t NOT IN (
                'delete_bitrix_task',
                'delete_crm_deal',
                'delete_crm_pipeline',
                'send_telegram_message',
                'list_telegram_contacts',
                'list_dialog_errors',
                'resolve_dialog_errors'
            )
       ),
       updated_at = now()
 WHERE slug = 'main'
   AND tools && ARRAY[
           'delete_bitrix_task',
           'delete_crm_deal',
           'delete_crm_pipeline',
           'send_telegram_message',
           'list_telegram_contacts',
           'list_dialog_errors',
           'resolve_dialog_errors'
       ]::text[];

COMMENT ON COLUMN agents.tools_mode IS
    'Откуда берётся набор инструментов: base — базовый минимум, max — весь реестр (новые '
    'инструменты подхватываются сами), custom — явный список из колонки tools. '
    'Заменил пресет по колонке tier (миграция 082, 07.08.2026).';
