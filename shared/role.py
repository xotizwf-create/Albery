"""Роль процесса: бот, веб или MCP.

Зачем. До 07.08.2026 приложение жило одним процессом (`run_5002.py`), который делал всё
сразу: отдавал сайт и API, принимал вебхуки Битрикса, обслуживал MCP, вёл разговоры ботов
и крутил все фоновые расписания. Один зависший ход мозга задерживал и сайт, и приём событий.

Разделяем по ролям, а не на N одинаковых воркеров, по конкретной причине. Накопление
сообщений (_B24_BATCHES), реестр живых ходов для кнопки «Новая сессия» (_LIVE_TURNS) и
восстановление прерванных ходов после рестарта — состояние В ПАМЯТИ, и все три приходят
через ОДИН вебхук `/bitrix/imbot/`. Пока эта роль однопроцессная, они работают как есть.
N одинаковых воркеров потребовали бы переноса самого хрупкого пути в системе (накопление
сообщений само было исправлением бага 23.07.2026, когда ответы агента накладывались друг
на друга) — риск, которого разделение по ролям просто не создаёт.

Фоновые расписания (автоматизации агентов, повторяющиеся задачи, обходы чекина, сторож
здоровья, синк системных автоматизаций) обязаны крутиться РОВНО в одном процессе. Раньше
каждое было за своим переключателем окружения; восемь переменных на службу — гарантированная
ошибка в конфиге, где забытая переменная даёт второй планировщик и двойные уведомления
людям. Поэтому переключатель один — ALBERY_ROLE, а частные остаются как аварийный выключатель.

Умолчание — `bot`, то есть без ALBERY_ROLE поведение ровно прежнее: одна служба делает всё.
"""
from __future__ import annotations

import os

ROLE_BOT = "bot"
ROLE_WEB = "web"
ROLE_MCP = "mcp"
KNOWN_ROLES = (ROLE_BOT, ROLE_WEB, ROLE_MCP)


def current_role() -> str:
    """Роль этого процесса. Неизвестное значение трактуем как `bot`.

    Именно так, а не падением: опечатка в unit-файле не должна оставить систему без
    планировщиков — лучше лишний раз выполнить работу в известном месте, чем не выполнить
    её нигде и узнать об этом через сутки по невыставленным задачам.
    """
    value = (os.getenv("ALBERY_ROLE") or "").strip().lower()
    return value if value in KNOWN_ROLES else ROLE_BOT


def is_bot() -> bool:
    return current_role() == ROLE_BOT


def background_jobs_enabled() -> bool:
    """Крутить ли в этом процессе фоновые расписания. Только в роли бота."""
    return is_bot()
