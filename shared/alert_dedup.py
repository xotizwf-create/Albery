"""Приглушение повторов в тревогах мониторинга.

16.08.2026, жалоба владельца: «постоянно приходят уведомления о каких-то сбоях».
Разбор показал не поток разных аварий, а одну и ту же болячку, которую антиспам не
узнавал в лицо. Набор проблем сравнивался как СЫРОЙ текст, а текст почти всегда несёт
изменчивый хвост: счётчик («таймауты ходов бота: 1» → «: 2»), процент диска, возраст
(«успешный ход 1 дн назад» → «2 дн назад»). Любое такое изменение давало новую подпись,
приглушение обнулялось, и монитор будил владельца заново — на пятиминутном расписании
это до двенадцати одинаковых сообщений в час.

Подпись строится по СМЫСЛУ набора: числа схлопываются, порядок не важен.
"""
from __future__ import annotations

import hashlib
import re
from typing import Iterable

_NUMBERS = re.compile(r"\d+")


def normalize_problem(text: str) -> str:
    """Текст проблемы без изменчивых чисел: «диск / заполнен на 86%» → «диск / заполнен на #%»."""
    return _NUMBERS.sub("#", " ".join(str(text).split()))


def alert_signature(problems: Iterable[str]) -> str:
    """Подпись набора проблем. Пустой набор — пустая подпись (сравнивать нечего)."""
    items = sorted(normalize_problem(p) for p in problems)
    if not items:
        return ""
    return hashlib.sha256("\n".join(items).encode("utf-8")).hexdigest()
