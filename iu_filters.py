"""Фильтры разговора: что не пускаем в модель и что не пускаем клиенту.

Владелец 26.07.2026: «обязательно реализовать фильтры. Заблокированные фразы: указываются слова
или фразы (по одной на строку), при наличии которых бот откажется отвечать. Вместо ответа клиент
получит стандартное сообщение о невозможности помочь по этой теме». Названные применения:
конкуренты, нецензурная лексика, темы вне бизнеса (политика, религия), попытки сломать промпт.

Почему фильтров не было вовсе. В старой системе единственным подобием фильтра была регулярка
`_OTHER_TOPIC_RE`, и та решала не «отвечать ли», а «не выслать ли по ошибке документ условий».
Ни списка запрещённых фраз, ни защиты от инъекций, ни проверки исходящего текста не существовало.

Про защиту от jailbreak важно понимать главное: список слов её не обеспечивает, он лишь
отсекает ленивые попытки. Настоящая защита — структурная и живёт в других слоях: у клиентского
рантайма нет инструментов (`tools=[]`), выход модели разбирается как строгий `TurnPlan`, и до
клиента доходит только поле `reply` после исходящей проверки. Даже успешно внушённая инструкция
не дотягивается ни до CRM, ни до документов.

Слой чистый: правила приходят параметром, ввода-вывода нет — поэтому всё проверяется тестами.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

# --- категории ---------------------------------------------------------------------------
PHRASE = "запрещённая фраза"
PROFANITY = "нецензурная лексика"
POLITICS = "тема вне бизнеса"
JAILBREAK = "попытка сломать промпт"
INTERNAL_LINK = "внутренний адрес портала"
LEAK = "утечка служебного текста"
CONCESSION = "уступка, которой нет в базе"

DEFAULT_REFUSAL = (
    "Извините, по этой теме я помочь не могу. Если у вас есть вопрос по индивидуальным "
    "условиям для продавцов Wildberries — с радостью отвечу."
)

# Корни, а не слова: русская брань живёт в приставках и окончаниях. Список намеренно короткий —
# он ловит явное, а тонкую настройку владелец делает своим списком фраз.
_PROFANITY_STEMS = (
    "хуй", "хуё", "хуе", "пизд", "ебат", "ебал", "ебан", "ебуч", "бляд", "блять",
    "муда", "мудо", "пидор", "пидар", "гандон", "гнид", "уёб", "уеб", "нахуй", "похуй",
)
# Приставка перед корнем обязана допускаться: «охуели», «заебал», «подъебка» — это тот же корень.
# Без неё фильтр пропускал ровно те формы, которыми в чате и ругаются.
_PROFANITY_RE = re.compile(
    r"(?<![а-яё])(?:о|за|на|по|при|у|вы|до|пере|раз|с|из|от|под|подъ|объ)?"
    r"(?:" + "|".join(_PROFANITY_STEMS) + r")",
    re.I,
)

# Политика и религия. Список узкий сознательно: широкий ловил бы обычные деловые фразы
# («партия товара», «вера в продукт») и молча отказывал бы живым клиентам.
_POLITICS_RE = re.compile(
    r"(?<![а-яё])(?:путин\w*|зеленск\w*|навальн\w*|выбор\w*\s+президент\w*|"
    r"сво\b|спецоперац\w*|мобилизац\w*|санкц\w*\s+против|"
    r"православ\w*|мусульман\w*|ислам\w*|христианств\w*|атеиз\w*|"
    r"библи\w*|коран\w*|церкв\w*|мечет\w*|молитв\w*)",
    re.I,
)

# Попытки перехватить управление. Ловим намерение, а не конкретную формулировку.
_JAILBREAK_RE = re.compile(
    r"(?:игнорир\w*|забудь|отмени|сбрось|не\s+обращай\s+внимани\w*)[^.!?\n]{0,40}"
    r"(?:инструкц\w*|правил\w*|промпт\w*|указани\w*|предыдущ\w*)|"
    r"(?:покажи|выведи|повтори|скажи|напечатай|назови)[^.!?\n]{0,30}"
    r"(?:системн\w*\s+промпт\w*|свой\s+промпт\w*|свои\s+инструкц\w*|"
    r"исходн\w*\s+инструкц\w*|системное\s+сообщени\w*)|"
    r"(?:ты|вы)\s+(?:—\s+|-\s+)?(?:бот|робот|нейросет\w*|ии|gpt|chatgpt|ai)\b[^.!?\n]{0,25}"
    r"(?:призна\w*|скажи\s+правду|не\s+вр\w*)|"
    r"(?:представь|вообрази|притворись|веди\s+себя)[^.!?\n]{0,30}"
    r"(?:что\s+ты|будто\s+ты|как\s+будто)|"
    r"\bDAN\b|\bjailbreak\w*|developer\s+mode|"
    r"ignore\s+(?:all\s+)?previous\s+instructions|"
    r"(?:system|initial)\s+prompt|you\s+are\s+now\b|act\s+as\s+(?:if|a)\b",
    re.I,
)

# Внутренние адреса портала: клиенту показываем ТОЛЬКО сайт компании (владелец, 22.07.2026).
_INTERNAL_URL_RE = re.compile(
    r"https?://\S*?(?:/pub/form/|/crm/|/company/personal/|/bitrix/|/workgroups/)\S*",
    re.I,
)

# Служебное, чего клиент видеть не должен: остатки старого протокола маркеров, куски JSON,
# трассировки и внутренние идентификаторы.
_LEAK_RE = re.compile(
    r"ПОКАЖИ_УСЛОВИЯ|НУЖЕН_ЧЕЛОВЕК|ТАКЖЕ_СПРОСИ_ЛЮДЕЙ|НЕТ_ОТВЕТА|"
    r'"next_action"|"source_ids"|"confidence"|'
    r"Traceback\s+\(most\s+recent\s+call\s+last\)|"
    r"(?<![а-яё])(?:source_id|deal_id|dialog_id|stage_id)\s*[:=]",
    re.I,
)

# Коммерческие уступки. Владелец 26.07.2026: «ей нельзя самостоятельно предлагать скидки и тд
# ни в коем случае, только то, что прописано в базе».
#
# Проверка не запрещает слова как таковые — она требует ИСТОЧНИКА. Если владелец сам написал в
# карточке про рассрочку, агент про неё расскажет; если не написал, а модель предложила — ход
# уходит человеку. «Индивидуальные условия» намеренно не считаются уступкой: это название
# продукта, а не подарок клиенту.
_CONCESSION_RE = re.compile(
    r"(?<![а-яё])(?:скидк\w*|дисконт\w*|снизим\w*|снижу|уступ\w*|уступк\w*|"
    r"бесплатн\w*|беспл\w*|бонус\w*|подар\w*|"
    r"рассрочк\w*|отсрочк\w*|льготн\w*|спецусловия|спец\.?\s*услови\w*|"
    r"персональн\w*\s+(?:услови\w*|цен[аыу]\w*|тариф\w*|скидк\w*)|"
    r"особы\w*\s+(?:услови\w*|цен[аыу]\w*|тариф\w*)|"
    r"пойд[её]м\s+навстречу|сделаем\s+исключени\w*|договоримся\s+о\s+цен\w*|"
    r"тестов\w*\s+период\w*|пробн\w*\s+период\w*|перв\w*\s+месяц\w*\s+бесплатн\w*)",
    re.I,
)
# «Индивидуальные условия» — рабочее название продукта, не уступка.
_PRODUCT_TERMS_RE = re.compile(r"индивидуальн\w*\s+услови\w*", re.I)

# Обещания выполненного действия. Проверяются не здесь, а оркестратором — он один знает, было ли
# действие на самом деле. Правило владельца 23.07.2026: «действие, потом слова».
_PROMISE_RE = re.compile(
    r"(?<![а-яё])(?:отправил\w*|выслал\w*|прислал\w*|передал\w*|создал\w*|подготовил\w*|"
    r"оформил\w*|назначил\w*|зарегистрировал\w*|добавил\w*|приложил\w*|сформировал\w*)",
    re.I,
)


@dataclass(frozen=True)
class Ruleset:
    """Настройка фильтров. Список фраз владелец правит в кабинете, остальное — выключатели."""

    phrases: tuple[str, ...] = ()
    block_profanity: bool = True
    block_politics: bool = True
    block_jailbreak: bool = True
    refusal: str = DEFAULT_REFUSAL


@dataclass(frozen=True)
class Hit:
    """Что сработало и на чём. Идёт в журнал и в карточку людям, но не клиенту."""

    category: str
    matched: str
    rule: str = ""

    def __bool__(self) -> bool:
        return True


def parse_phrases(raw: str) -> tuple[str, ...]:
    """Список запрещённых фраз: по одной на строку, как просил владелец.

    Пустые строки и строки-комментарии (`#`) пропускаются, чтобы список можно было
    структурировать заголовками, не ломая фильтр."""
    out = []
    for line in str(raw or "").replace("\r\n", "\n").split("\n"):
        item = line.strip()
        if not item or item.startswith("#"):
            continue
        out.append(item)
    return tuple(out)


def _phrase_pattern(phrase: str) -> re.Pattern:
    """Фраза владельца → шаблон. `re:` в начале строки означает готовую регулярку.

    Обычная фраза ищется по границам слова: «ozon» не должен срабатывать внутри «horizontal»,
    иначе фильтр начнёт молча отказывать живым клиентам."""
    item = phrase.strip()
    if item.lower().startswith("re:"):
        return re.compile(item[3:].strip(), re.I)
    body = re.escape(item)
    # Пробелы во фразе владельца допускают любой пробельный разделитель.
    body = body.replace(r"\ ", r"\s+")
    return re.compile(rf"(?<![\w]){body}(?![\w])", re.I)


def check_incoming(text: str, rules: Ruleset) -> Hit | None:
    """Проверить сообщение клиента ДО вызова модели.

    Совпало — модель не зовём вовсе: это и дешевле, и надёжнее, чем надеяться, что она
    откажется сама."""
    value = str(text or "")
    if not value.strip():
        return None

    for phrase in rules.phrases:
        try:
            pattern = _phrase_pattern(phrase)
        except re.error:
            # Битую регулярку владельца молча игнорируем: один неверный символ в списке не
            # должен отключать весь фильтр.
            continue
        match = pattern.search(value)
        if match:
            return Hit(PHRASE, match.group(0), rule=phrase)

    if rules.block_jailbreak:
        match = _JAILBREAK_RE.search(value)
        if match:
            return Hit(JAILBREAK, match.group(0))
    if rules.block_profanity:
        match = _PROFANITY_RE.search(value)
        if match:
            return Hit(PROFANITY, match.group(0))
    if rules.block_politics:
        match = _POLITICS_RE.search(value)
        if match:
            return Hit(POLITICS, match.group(0))
    return None


def check_outgoing(text: str, rules: Ruleset) -> Hit | None:
    """Проверить текст ПЕРЕД отправкой клиенту.

    Входящий фильтр не спасает от того, что модель напишет сама: внутренний адрес портала,
    остаток служебного протокола или брань в пересказе цитаты клиента."""
    value = str(text or "")
    if not value.strip():
        return None

    match = _INTERNAL_URL_RE.search(value)
    if match:
        return Hit(INTERNAL_LINK, match.group(0))
    match = _LEAK_RE.search(value)
    if match:
        return Hit(LEAK, match.group(0))
    if rules.block_profanity:
        match = _PROFANITY_RE.search(value)
        if match:
            return Hit(PROFANITY, match.group(0))
    for phrase in rules.phrases:
        try:
            pattern = _phrase_pattern(phrase)
        except re.error:
            continue
        match = pattern.search(value)
        if match:
            return Hit(PHRASE, match.group(0), rule=phrase)
    return None


def concession(text: str, sources: str) -> Hit | None:
    """Предложила ли модель уступку, которой нет в базе знаний.

    Владелец 26.07.2026: «ей нельзя самостоятельно предлагать скидки и тд ни в коем случае,
    только то, что прописано в базе». Поэтому проверка не на слово, а на ИСТОЧНИК: та же
    «рассрочка» разрешена, если владелец написал про неё в карточке, и запрещена, если модель
    придумала её сама."""
    value = str(text or "")
    # Название продукта вырезаем до поиска, иначе «индивидуальные условия» читались бы как
    # обещание особых условий этому клиенту.
    probe = _PRODUCT_TERMS_RE.sub(" ", value)
    known = _PRODUCT_TERMS_RE.sub(" ", str(sources or "")).casefold()
    for match in _CONCESSION_RE.finditer(probe):
        word = match.group(0)
        # Достаточно, чтобы корень уступки встречался в источниках: владелец мог написать
        # «скидок нет» — тогда слово «скидка» в ответе опирается на базу.
        stem = word.casefold()[:5]
        if stem and stem in known:
            continue
        return Hit(CONCESSION, word)
    return None


def claims_action(text: str) -> str:
    """Заявлено ли в тексте выполненное действие. Пусто — не заявлено.

    Оркестратор сверяет это с тем, что действительно исполнилось: «отправил договор», когда
    договор не собран, — та самая ошибка, за которую владелец отдельно ругал 23.07.2026."""
    match = _PROMISE_RE.search(str(text or ""))
    return match.group(0) if match else ""
