"""WSGI-вход для служб ВЕБ и MCP (gunicorn).

Роль бота запускается отдельно, через run_5002.py, и это осознанно. У неё есть собственный
слив при остановке: ход мозга живёт в фоновом потоке ПОСЛЕ ответа на вебхук, поэтому обычный
graceful-timeout gunicorn его не покрывает — нужен свой SIGTERM-обработчик, который ждёт
опустошения bitrix_inflight_turns. Переносить эту проверенную логику в хуки gunicorn заодно
с разделением служб — значит трогать самый деликатный путь остановки в один заход с
переездом. Роль бота однопроцессная, и боевой сервер даёт ей меньше всего: её вебхуки
внутренние и редкие, тогда как публичные веб и MCP выигрывают сразу.

Здесь намеренно НЕ выставляется ALBERY_WEB_PROCESS: стартовые процедуры (регистрация команд
ботов, восстановление прерванных ходов с уведомлением людей «я перезапустился») обязаны
выполняться ровно в одном процессе — в роли бота.
"""
from __future__ import annotations

import os

from shared.role import KNOWN_ROLES, ROLE_BOT, current_role

SERVED_ROLES = tuple(r for r in KNOWN_ROLES if r != ROLE_BOT)


def check_role(declared: str | None) -> str:
    """Проверить роль ДО импорта приложения. Возвращает нормализованную роль или бросает.

    Именно бросает, а не подставляет умолчание: запуск с неверной ролью дал бы
    полуработающую службу — без стартовых процедур (их ставит run_5002.py), но с фоновыми
    расписаниями (они включены в роли `bot`). Такая служба выглядела бы живой и при этом
    слала бы людям вторые копии уведомлений.
    """
    value = (declared or "").strip().lower()
    if value not in SERVED_ROLES:
        raise RuntimeError(
            "wsgi.py обслуживает только роли web и mcp: задайте ALBERY_ROLE=web или "
            f"ALBERY_ROLE=mcp. Сейчас ALBERY_ROLE={value!r}. Роль бота поднимается через "
            "run_5002.py — у неё свой слив живых ходов при остановке."
        )
    return value


check_role(os.getenv("ALBERY_ROLE"))

from app import app  # noqa: E402  — импорт только после проверки роли

application = app

__all__ = ["app", "application", "current_role"]
