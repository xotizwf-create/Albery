"""Правила воронки как ДАННЫЕ: снимок фактов → решение, с указанием, какое правило сработало.

Владелец 25.07.2026: «хватит фиксить каждый шаг по отдельности, нужно менять схему на корню».

Почему так. Правила поведения жили россыпью `if`-ов внутри длинных функций отправки. Каждое
по отдельности было верным, но они пересекались, и новая защита молча выключала прежнее
поведение — за одни сутки это случилось трижды (замолчал сторож анкеты; «Уточню у команды» в
ответ на «Все верно»; тупик на этапе без шага). Увидеть это в коде было нельзя: условия
разбросаны, приоритет задавался порядком строк.

Как здесь. Правило — объект: условие, действие, приоритет и ПРИЧИНА появления (дата + живой
случай). Решение принимается перебором правил по приоритету, и наружу отдаётся не только
действие, но и правило, которое сработало — это основа объяснимости (кто и почему так решил).
Слой чистый: никакого ввода-вывода, только факты на входе и решение на выходе. Поэтому он
целиком проверяем тестами, а прод-код лишь исполняет решение.

Читать вместе с `docs/funnel-state-machine.md` (состояния и инварианты) и `docs/tone-of-voice.md`.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from typing import Callable

# Этапы воронки — ЗДЕСЬ единственное место, где они заданы: и правила, и код отправки берут их
# отсюда. Раньше список этапов сверки жил отдельно от констант, и они разошлись (24.07.2026:
# склейка ставила «Анкета заполнена», а сторож этот этап не считал этапом сверки).
STAGE_NEW = os.getenv("CRM_STAGE_NEW", "C16:NEW").strip()
STAGE_CONTACTED = os.getenv("CRM_STAGE_CONTACTED", "C16:CONTACTED").strip()
STAGE_FORM_DONE = os.getenv("CRM_STAGE_FORM_DONE", "C16:UC_ANKETA").strip()
STAGE_TERMS = os.getenv("CRM_STAGE_TERMS", "C16:S84294149").strip()

# --- действия ---------------------------------------------------------------------------------
OPEN_DEAL = "открыть сделку на «Новом лиде»"
SEND_TERMS = "отправить условия дословно из документа"
ANSWER_QUESTIONS = "ответить на вопросы по источникам, остальное — людям"
TERMS_TO_HUMANS = "вопрос поверх условий — людям, клиенту короткая строка"
CONTINUE_STEP = "вести разговор по текущему шагу воронки"
SEND_SURVEY = "отправить сверку анкеты"
STAY_SILENT = "ничего не отправлять"

# Этапы, на которых сверка анкеты ещё уместна. «Анкета заполнена» входит обязательно: именно на
# него склейка ставит сделку (без него сторож молчал — регрессия 24.07.2026).
SURVEY_STAGES = (STAGE_NEW, STAGE_CONTACTED, STAGE_FORM_DONE)

# Человек интересуется подключением к ИУ, а не просто пишет на аккаунт.
IU_INTENT_RE = re.compile(
    r"\bи\.?у\b|индивидуальн\w* услови|подключ\w*|присоедин\w*|услови\w*|комисси\w*|"
    r"тариф\w*|сотрудничеств\w*|сколько стоит|цен[аыу]\b|прайс", re.I)
# Просьба выслать документ заново — это не вопрос поверх условий.
RESEND_RE = re.compile(
    r"ещ[её]\s+раз|повтор\w*|продублир\w*|снова|заново|не\s+приш\w*|не\s+получ\w*|"
    r"не\s+открыв\w*|не\s+вид\w*\s+(файл|документ|сообщ)", re.I)
# Вопрос ли это. Нужно, чтобы людям уходили ВОПРОСЫ, а не «ок», «да», «все верно».
QUESTION_RE = re.compile(
    r"\?|\bкак(ой|ая|ие|ое|ов)?\b|\bсколько\b|\bчто\b|\bпочему\b|\bзачем\b|\bкогда\b|"
    r"\bгде\b|\bкуда\b|\bчем\b|\bможно ли\b|\bа если\b|\bнасколько\b|\bкакова\b", re.I)
# Клиент НЕДОВОЛЕН: скоростью, сервисом, отношением. 25.07.2026 (диалог 377640060): «Но вы
# какие-то супер не торопливые..» — это не вопрос про условия, а претензия. Документом её закрывать
# нельзя: недовольство обрабатывает живой человек, иначе клиент уходит.
COMPLAINT_RE = re.compile(
    r"не\s*тороп\w*|долго\s+(ждать|отвеча|молч)|сколько\s+(уже\s+)?ждать|игнор\w*|"
    r"никто\s+не\s+отвеча\w*|вы\s+(вообще\s+)?работаете|это\s+несерьёзн\w*|"
    r"так\s+не\s+работа\w*|неуважени\w*", re.I)
# Просьба про договор или реквизиты — это ШАГ ВОРОНКИ (сбор реквизитов, сборка договора), а не
# ответ по документу условий. 25.07.2026 (диалог 256942600) на «Можете прислать договор?» агент
# ответил цитатой про NDA — уход от вопроса вместо действия.
CONTRACT_RE = re.compile(
    r"договор\w*|реквизит\w*|счёт\s+на\s+оплату|подписа\w+\s+документ", re.I)
# Клиент СПОРИТ с цифрами или расчётом. 25.07.2026 (диалог 256942600): «Вы не правильно пишите,
# вычитаете 44% не с „к перечислению WB“, а от продаж -44%» — агент в ответ выслал весь документ
# условий. Возражение по расчёту документом не закрывается: это разговор с живым человеком.
DISPUTE_RE = re.compile(
    r"не\s*правильн\w*|неправильн\w*|не\s+так\s+счита|неверн\w*\s+счита|вы\s+счита\w+\s+не|"
    r"вычита\w+\s+не|это\s+не\s+так|ошиб\w*\s+в\s+расч|путае\w+", re.I)


@dataclass(frozen=True)
class Facts:
    """Снимок состояния на один ход. Собирается ОДИН раз, дальше решения читают только его.

    Раньше каждая проверка сама лазила в CRM, состояние и журнал — и разные части хода могли
    видеть разную картину."""
    uid: int = 0
    name: str = ""
    username: str = ""
    text: str = ""                    # вся пачка сообщений клиента одной строкой
    deal_id: int | None = None
    stage: str = ""
    anketa: str = ""                  # готовый текст сверки, "" если анкеты ещё нет
    anketa_fingerprint: str = ""
    anketa_seen: str = ""             # отпечаток уже сверенных данных
    legacy_surveyed: bool = False     # сверку отправляли до перехода на отпечатки
    terms_sent: bool = False
    first_contact: bool = True
    wants_terms: bool = False         # модель вернула маркер ПОКАЖИ_УСЛОВИЯ

    # --- производные признаки: считаются из текста один раз и читаются по имени ---------------
    @property
    def iu_intent(self) -> bool:
        return bool(IU_INTENT_RE.search(self.text or ""))

    @property
    def asks_to_resend(self) -> bool:
        return bool(RESEND_RE.search(self.text or ""))

    @property
    def is_question(self) -> bool:
        return bool(QUESTION_RE.search(self.text or ""))

    @property
    def disputes_numbers(self) -> bool:
        return bool(DISPUTE_RE.search(self.text or ""))

    @property
    def complains(self) -> bool:
        return bool(COMPLAINT_RE.search(self.text or ""))

    @property
    def asks_contract(self) -> bool:
        return bool(CONTRACT_RE.search(self.text or ""))

    @property
    def anketa_is_new(self) -> bool:
        return bool(self.anketa) and self.anketa_fingerprint != self.anketa_seen


@dataclass(frozen=True)
class Rule:
    """Правило поведения: условие → действие, с причиной появления."""
    name: str
    slot: str                         # "message" — ход по сообщению клиента, "watch" — сторож
    action: str
    when: Callable[[Facts], bool]
    origin: str                       # дата и живой случай: зачем правило появилось
    priority: int = 100


@dataclass(frozen=True)
class Decision:
    """Что делаем и по какому правилу. Правило нужно для объяснимости и разбора."""
    action: str
    rule: str = ""
    origin: str = ""
    facts: Facts = field(default_factory=Facts)


# --- РЕЕСТР ----------------------------------------------------------------------------------
# Порядок в списке не важен: приоритет задан числом, меньше — раньше. Это осознанно: раньше
# приоритет задавался порядком строк в функции, и вставка нового условия меняла поведение
# соседних.
RULES: tuple[Rule, ...] = (
    # --- ход по сообщению клиента ------------------------------------------------------------
    Rule("условия ещё не отправляли", "message", SEND_TERMS,
         lambda f: f.wants_terms and not f.terms_sent,
         "23.07.2026: модель пересказывала условия своими словами, цифры гуляли от диалога к "
         "диалогу («200 000 ₽ вместо 500 000» в одном чате, «комиссия 44%» в другом)",
         priority=10),
    Rule("просят выслать условия заново", "message", SEND_TERMS,
         lambda f: f.wants_terms and f.terms_sent and f.asks_to_resend,
         "24.07.2026: «пришлите ещё раз» — это просьба о документе, а не вопрос поверх него",
         priority=20),
    Rule("вопросы поверх отправленных условий", "message", ANSWER_QUESTIONS,
         lambda f: f.wants_terms and f.terms_sent and f.is_question,
         "25.07.2026, диалог 764181402: «Какой дрр нужно держать и как происходит управление? "
         "+какая комиссия ваша по партнерской этой программе?» — три вопроса в одном сообщении. "
         "Про комиссию ответ в документе ЕСТЬ, про ДРР и управление нет; клиент не получал ни "
         "одного ответа. Отвечаем на что знаем, остальное уносим людям",
         priority=30),
    Rule("клиент недоволен сервисом", "message", TERMS_TO_HUMANS,
         lambda f: f.complains,
         "25.07.2026, диалог 377640060: «Но вы какие-то супер не торопливые..» — претензия после "
         "того, как три хода упали на сбое модели. Недовольство обрабатывает живой человек, "
         "документом его не закрыть",
         priority=1),
    Rule("просит договор или говорит про реквизиты", "message", CONTINUE_STEP,
         lambda f: f.asks_contract and not f.disputes_numbers,
         "25.07.2026, диалог 256942600: на «Можете прислать договор?» агент ответил цитатой про "
         "NDA. Договор и реквизиты — это шаг воронки (send_contract), а не ответ по документу "
         "условий: шаг сам скажет, что делать",
         priority=6),
    Rule("спорит с расчётом или цифрами", "message", TERMS_TO_HUMANS,
         lambda f: f.disputes_numbers,
         "25.07.2026, диалог 256942600: «Вы не правильно пишите, вычитаете 44% не с „к "
         "перечислению WB“, а от продаж -44%» — агент в ответ выслал весь документ условий. "
         "Возражение по расчёту документом не закрывается: это разговор с живым человеком",
         priority=3),
    Rule("подтверждение без интереса к ИУ", "message", CONTINUE_STEP,
         lambda f: f.wants_terms and not f.terms_sent and not (f.is_question or f.iu_intent),
         "25.07.2026: на «Поняла, спасибо» реестр был готов выслать документ условий — маркер "
         "модели не повод вываливать документ, если человек ни о чём не спросил",
         priority=5),
    Rule("подтверждение, а не вопрос", "message", CONTINUE_STEP,
         lambda f: f.wants_terms and f.terms_sent and not f.is_question,
         "24.07.2026, Александр, сделка 148: на «Все верно» клиент получил «Уточню это у "
         "команды и вернусь с ответом» — маркер условий сработал вхолостую",
         priority=40),
    Rule("интерес к ИУ без сделки", "message", OPEN_DEAL,
         lambda f: f.iu_intent and not f.deal_id,
         "24.07.2026: 4 из 7 диалогов шли БЕЗ СДЕЛКИ, и до анкеты у агента не было шага вовсе — "
         "он импровизировал и обещал невыполнимое",
         priority=50),
    Rule("разговор без интереса к ИУ", "message", CONTINUE_STEP,
         lambda f: True,
         "24.07.2026, решение владельца: на аккаунт пишут поставщики и знакомые — им в воронке "
         "не место, но отвечать им надо",
         priority=900),

    # --- сторож анкеты -----------------------------------------------------------------------
    Rule("анкета появилась, данные новые", "watch", SEND_SURVEY,
         lambda f: (f.anketa_is_new and not f.legacy_surveyed
                    and f.stage in SURVEY_STAGES),
         "24.07.2026: агент должен сам замечать заполненную анкету, а не ждать сообщения "
         "клиента; признак — САМИ ДАННЫЕ анкеты, потому что сделку теперь заводит агент",
         priority=10),
    Rule("эти данные анкеты уже сверяли", "watch", STAY_SILENT,
         lambda f: bool(f.anketa) and not f.anketa_is_new,
         "24.07.2026: одна анкета = одна сверка; перезаполнил — отпечаток другой, сверяем заново",
         priority=20),
    Rule("сверку отправляли до перехода на отпечатки", "watch", STAY_SILENT,
         lambda f: f.legacy_surveyed,
         "24.07.2026: при переходе на отпечатки нельзя заново сверять тех, кому сверку уже "
         "отправляли",
         priority=30),
    Rule("сделка ушла дальше сверки", "watch", STAY_SILENT,
         lambda f: bool(f.anketa) and f.stage not in SURVEY_STAGES,
         "24.07.2026: на условиях и договоре сверка анкеты уже не к месту",
         priority=40),
    Rule("анкеты ещё нет", "watch", STAY_SILENT,
         lambda f: True,
         "24.07.2026: сверка без данных — это сообщение ни о чём",
         priority=900),
)


def decide(facts: Facts, slot: str = "message") -> Decision:
    """Первое подходящее правило по приоритету. Возвращает и решение, и его причину."""
    for rule in sorted((r for r in RULES if r.slot == slot), key=lambda r: r.priority):
        if rule.when(facts):
            return Decision(action=rule.action, rule=rule.name, origin=rule.origin, facts=facts)
    return Decision(action=STAY_SILENT, rule="нет подходящего правила", facts=facts)


def explain(decision: Decision) -> str:
    """Строка для журнала: что решили, по какому правилу и на каких фактах."""
    f = decision.facts
    return (f"решение: {decision.action} | правило: {decision.rule} | "
            f"сделка={f.deal_id} этап={f.stage or '—'} условия_отправлены={f.terms_sent} "
            f"вопрос={f.is_question} анкета={'новая' if f.anketa_is_new else 'нет/старая'}")
